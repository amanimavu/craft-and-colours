export function getShippingCountry(code: string): ShippingCountry {
  return (
    SHIPPING_COUNTRIES.find((country) => country.code === code) ??
    SHIPPING_COUNTRIES[0]
  );
}

export function regionName(countryCode: string, regionCode: string): string {
  return (
    getShippingCountry(countryCode).regions.find(
      (region) => region.code === regionCode,
    )?.name ?? regionCode
  );
}
