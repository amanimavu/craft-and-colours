// Countries the shop delivers to, with WooCommerce's own region codes
// (woocommerce/i18n/states.php). The Store API rejects any other `state`
// value as an invalid address, so never hand-write these. Regenerate from the
// installed WooCommerce if it adds or renames regions.

export interface Region {
  code: string;
  name: string;
}

export interface ShippingCountry {
  code: 'KE' | 'UG' | 'TZ';
  name: string;
  /** Label WooCommerce uses for `state` in this country. */
  regionLabel: string;
  /** Pre-selected region, or '' to make the customer choose. */
  defaultRegion: string;
  /**
   * Optional where the plugin relaxes it (KE, TZ — includes/address-fields.php);
   * WooCommerce hides it for Uganda.
   */
  postcode: 'optional' | 'hidden';
  regions: Region[];
}

